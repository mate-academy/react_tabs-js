// 1 Використовуємо деструктуризацію для отримання пропсів:
// 'tabs' - масив даних, 'activeTabId' - рядок з ID, 'onTabSelected' - функція-обробник.
export const Tabs = ({ tabs, activeTabId, onTabSelected }) => {
  // 2 Шукаємо в масиві об'єкт, чий 'id' збігається з тим, що ми отримали.
  // Якщо activeTabId порожній або неправильний, 'find' поверне undefined.
  // Тоді спрацює оператор '||' (АБО) і ми візьмемо першу вкладку масиву [0].
  const activeTab = tabs.find(tab => tab.id === activeTabId) || tabs[0];

  return (
    <>
      {' '}
      {/* 3 Фрагмент: дозволяє повернути два сусідні блоки (меню і контент) як одне ціле. */}
      <div className="tabs is-boxed">
        {' '}
        {/* 4 Обгортка для стилів Bulma (робить вкладки в рамках). */}
        <ul>
          {/* 5 Метод .map() перетворює кожен об'єкт вкладки на елемент списку <li>. */}
          {tabs.map(tab => (
            <li
              key={tab.id} // 6 Унікальний ключ: допомагає React розуміти, який саме елемент змінився.
              // 7 Динамічний клас: якщо id цієї вкладки збігається з активним id,
              // Bulma підсвітить її як вибрану за допомогою 'is-active'.
              className={tab.id === activeTab.id ? 'is-active' : ''}
              data-cy="Tab" // Для тестів.
            >
              <a
                href={`#${tab.id}`} // 8 Посилання на якір (id вкладки).
                data-cy="TabLink"
                onClick={event => {
                  // 9 Зупиняємо перехід за посиланням, щоб сторінка не "стрибала".
                  event.preventDefault();

                  // 10 "Захист від зайвих дій": викликаємо функцію зміни лише якщо
                  // ми натиснули на вкладку, яка НЕ є активною зараз.
                  if (tab.id !== activeTab.id) {
                    onTabSelected(tab.id);
                  }
                }}
              >
                {tab.title}
                {/* 11 Виводимо назву (напр. "Tab 1"). */}
              </a>
            </li>
          ))}
        </ul>
      </div>
      {/* 12 Блок контенту: беремо поле 'content' саме з того об'єкта, який ми знайшли в п. 2 */}
      <div className="block" data-cy="TabContent">
        {activeTab.content}
      </div>
    </>
  );
};
